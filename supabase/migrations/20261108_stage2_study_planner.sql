do $$
declare t text;
begin
  foreach t in array array['ha_study_items','ha_study_settings','ha_study_done','ha_user_notifications','ha_push_subs'] loop
    execute format('drop policy if exists teacher_all on public.%I', t);
    execute format('create policy teacher_all on public.%I for all to authenticated using (public.ha_is_teacher()) with check (public.ha_is_teacher())', t);
  end loop;
end $$;

create or replace function public.ha_study_occurs(p_enabled boolean, p_repeat text, p_days int[], p_once date, rest int[], d date)
returns boolean language sql immutable set search_path = '' as $$
  select p_enabled and case p_repeat
    when 'once' then p_once = d
    when 'daily' then not (extract(dow from d)::int = any(rest))
    else (extract(dow from d)::int = any(p_days)) and not (extract(dow from d)::int = any(rest))
  end;
$$;

-- Student RPCs
create or replace function public.ha_study_get(p_code text, p_device text)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare c public.ha_codes; s public.ha_study_settings;
begin
  c := public.ha_resolve(p_code, p_device);
  if c.code is null then return jsonb_build_object('ok', false, 'error', 'UNAUTHORIZED'); end if;
  select * into s from public.ha_study_settings where code = c.code;
  return jsonb_build_object('ok', true,
    'settings', jsonb_build_object('tz', coalesce(s.tz, 'Africa/Cairo'), 'restDays', to_jsonb(coalesce(s.rest_days, '{}'::int[])),
      'notifyEnabled', coalesce(s.notify_enabled, true), 'dailySummary', coalesce(s.daily_summary, true),
      'summaryTime', to_char(coalesce(s.summary_time, '07:00'::time), 'HH24:MI')),
    'items', coalesce((select jsonb_agg(jsonb_build_object('id', i.id, 'title', i.title, 'subject', i.subject, 'lessonId', i.lesson_id, 'kind', i.kind,
        'repeat', i.repeat, 'days', to_jsonb(i.days), 'onceDate', i.once_date, 'startTime', to_char(i.start_time, 'HH24:MI'),
        'endTime', to_char(i.end_time, 'HH24:MI'), 'remindBeforeMin', i.remind_before_min, 'enabled', i.enabled) order by i.start_time)
      from public.ha_study_items i where i.code = c.code), '[]'::jsonb),
    'done', coalesce((select jsonb_agg(jsonb_build_object('itemId', d.item_id, 'day', d.day))
      from public.ha_study_done d join public.ha_study_items i on i.id = d.item_id
      where i.code = c.code and d.day >= current_date - 14), '[]'::jsonb),
    'notifications', coalesce((select jsonb_agg(jsonb_build_object('id', n.id, 'kind', n.kind, 'title', n.title, 'body', n.body, 'createdAt', n.created_at, 'read', n.read_at is not null) order by n.created_at desc)
      from (select * from public.ha_user_notifications where code = c.code order by created_at desc limit 40) n), '[]'::jsonb),
    'unread', (select count(*) from public.ha_user_notifications where code = c.code and read_at is null),
    'pushDevices', (select count(*) from public.ha_push_subs where code = c.code));
end $$;

create or replace function public.ha_study_save_item(p_code text, p_device text, p_item jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare c public.ha_codes; rid uuid; id_in uuid; n int;
  v_title text := trim(coalesce(p_item ->> 'title', ''));
  v_repeat text := coalesce(p_item ->> 'repeat', 'weekly');
  v_days int[] := coalesce((select array_agg(x::int) from jsonb_array_elements_text(coalesce(p_item -> 'days', '[]'::jsonb)) x where x ~ '^[0-6]$'), '{}');
  v_start time; v_end time; v_once date;
begin
  c := public.ha_resolve(p_code, p_device);
  if c.code is null then return jsonb_build_object('ok', false, 'error', 'UNAUTHORIZED'); end if;
  begin
    v_start := (p_item ->> 'startTime')::time;
    v_end := nullif(p_item ->> 'endTime', '')::time;
    v_once := nullif(p_item ->> 'onceDate', '')::date;
    id_in := nullif(p_item ->> 'id', '')::uuid;
  exception when others then return jsonb_build_object('ok', false, 'error', 'INVALID'); end;
  if v_title = '' or length(v_title) > 120 or v_start is null or v_repeat not in ('once','daily','weekly')
     or (v_end is not null and v_end <= v_start) or (v_repeat = 'once' and v_once is null)
     or (v_repeat = 'weekly' and cardinality(v_days) = 0) then
    return jsonb_build_object('ok', false, 'error', 'INVALID');
  end if;
  if id_in is null then
    select count(*) into n from public.ha_study_items where code = c.code;
    if n >= 100 then return jsonb_build_object('ok', false, 'error', 'LIMIT'); end if;
    insert into public.ha_study_items (code, title, subject, lesson_id, kind, repeat, days, once_date, start_time, end_time, remind_before_min, enabled)
      values (c.code, v_title, left(coalesce(nullif(trim(p_item ->> 'subject'), ''), 'فيزياء'), 60), nullif(left(coalesce(p_item ->> 'lessonId', ''), 80), ''),
              case when p_item ->> 'kind' = 'task' then 'task' else 'study' end, v_repeat, v_days, v_once, v_start, v_end,
              least(greatest(coalesce((p_item ->> 'remindBeforeMin')::int, 10), 0), 180), coalesce((p_item ->> 'enabled')::boolean, true))
      returning id into rid;
  else
    update public.ha_study_items set title = v_title, subject = left(coalesce(nullif(trim(p_item ->> 'subject'), ''), 'فيزياء'), 60),
        lesson_id = nullif(left(coalesce(p_item ->> 'lessonId', ''), 80), ''), kind = case when p_item ->> 'kind' = 'task' then 'task' else 'study' end,
        repeat = v_repeat, days = v_days, once_date = v_once, start_time = v_start, end_time = v_end,
        remind_before_min = least(greatest(coalesce((p_item ->> 'remindBeforeMin')::int, 10), 0), 180),
        enabled = coalesce((p_item ->> 'enabled')::boolean, true), updated_at = now()
      where id = id_in and code = c.code returning id into rid;
    if rid is null then return jsonb_build_object('ok', false, 'error', 'NOT_FOUND'); end if;
  end if;
  return jsonb_build_object('ok', true, 'id', rid);
end $$;

create or replace function public.ha_study_delete_item(p_code text, p_device text, p_id uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare c public.ha_codes;
begin
  c := public.ha_resolve(p_code, p_device);
  if c.code is null then return jsonb_build_object('ok', false, 'error', 'UNAUTHORIZED'); end if;
  delete from public.ha_study_items where id = p_id and code = c.code;
  return jsonb_build_object('ok', true);
end $$;

create or replace function public.ha_study_set_done(p_code text, p_device text, p_id uuid, p_day date, p_done boolean)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare c public.ha_codes; tz text; today date;
begin
  c := public.ha_resolve(p_code, p_device);
  if c.code is null then return jsonb_build_object('ok', false, 'error', 'UNAUTHORIZED'); end if;
  if not exists (select 1 from public.ha_study_items where id = p_id and code = c.code) then return jsonb_build_object('ok', false, 'error', 'NOT_FOUND'); end if;
  select coalesce((select s.tz from public.ha_study_settings s where s.code = c.code), 'Africa/Cairo') into tz;
  today := (now() at time zone tz)::date;
  if p_day is null or p_day > today or p_day < today - 7 then return jsonb_build_object('ok', false, 'error', 'INVALID'); end if;
  if p_done then
    insert into public.ha_study_done (item_id, day) values (p_id, p_day) on conflict do nothing;
  else
    delete from public.ha_study_done where item_id = p_id and day = p_day;
  end if;
  return jsonb_build_object('ok', true);
end $$;

create or replace function public.ha_study_save_settings(p_code text, p_device text, p_tz text, p_rest int[], p_notify boolean, p_summary boolean, p_summary_time text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare c public.ha_codes; st time;
begin
  c := public.ha_resolve(p_code, p_device);
  if c.code is null then return jsonb_build_object('ok', false, 'error', 'UNAUTHORIZED'); end if;
  if not exists (select 1 from pg_timezone_names where name = coalesce(p_tz, '')) then return jsonb_build_object('ok', false, 'error', 'INVALID'); end if;
  begin st := coalesce(nullif(p_summary_time, ''), '07:00')::time; exception when others then return jsonb_build_object('ok', false, 'error', 'INVALID'); end;
  insert into public.ha_study_settings (code, tz, rest_days, notify_enabled, daily_summary, summary_time, updated_at)
    values (c.code, p_tz, coalesce((select array_agg(x) from unnest(coalesce(p_rest, '{}')) x where x between 0 and 6), '{}'), coalesce(p_notify, true), coalesce(p_summary, true), st, now())
    on conflict (code) do update set tz = excluded.tz, rest_days = excluded.rest_days, notify_enabled = excluded.notify_enabled,
      daily_summary = excluded.daily_summary, summary_time = excluded.summary_time, updated_at = now();
  return jsonb_build_object('ok', true);
end $$;

