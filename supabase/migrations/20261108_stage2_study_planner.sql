-- Stage 2 / System 2: study planner + server-side reminders (pg_cron -> in-app notifications -> Web Push via edge function).
-- Reminders are created by the database on a schedule, so they fire even when the student's browser is closed.

create extension if not exists pg_cron;
create extension if not exists pg_net with schema extensions;

create table if not exists public.ha_study_items (
  id uuid primary key default gen_random_uuid(),
  code text not null,
  title text not null check (length(title) between 1 and 120),
  subject text not null default 'فيزياء' check (length(subject) <= 60),
  lesson_id text,
  kind text not null default 'study' check (kind in ('study','task')),
  repeat text not null default 'weekly' check (repeat in ('once','daily','weekly')),
  days int[] not null default '{}',
  once_date date,
  start_time time not null,
  end_time time,
  remind_before_min int not null default 10 check (remind_before_min between 0 and 180),
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (end_time is null or end_time > start_time),
  check (repeat <> 'once' or once_date is not null)
);
create index if not exists ha_study_items_code on public.ha_study_items (code);

create table if not exists public.ha_study_settings (
  code text primary key,
  tz text not null default 'Africa/Cairo',
  rest_days int[] not null default '{}',
  notify_enabled boolean not null default true,
  daily_summary boolean not null default true,
  summary_time time not null default '07:00',
  updated_at timestamptz not null default now()
);

create table if not exists public.ha_study_done (
  item_id uuid not null references public.ha_study_items(id) on delete cascade,
  day date not null,
  done_at timestamptz not null default now(),
  primary key (item_id, day)
);

create table if not exists public.ha_user_notifications (
  id uuid primary key default gen_random_uuid(),
  code text not null,
  kind text not null,
  title text not null,
  body text not null,
  item_id uuid,
  dedupe_key text not null unique,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  pushed_at timestamptz
);
create index if not exists ha_user_notifications_code on public.ha_user_notifications (code, created_at desc);
create index if not exists ha_user_notifications_unpushed on public.ha_user_notifications (created_at) where pushed_at is null;

create table if not exists public.ha_push_subs (
  id uuid primary key default gen_random_uuid(),
  code text not null,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  created_at timestamptz not null default now()
);
create index if not exists ha_push_subs_code on public.ha_push_subs (code);

-- VAPID keys are generated by the edge function on first use and never leave the server.
create table if not exists public.ha_push_config (
  id int primary key default 1 check (id = 1),
  public_key text not null,
  private_key text not null,
  created_at timestamptz not null default now()
);

alter table public.ha_study_items enable row level security;
alter table public.ha_study_settings enable row level security;
alter table public.ha_study_done enable row level security;
alter table public.ha_user_notifications enable row level security;
alter table public.ha_push_subs enable row level security;
alter table public.ha_push_config enable row level security;
