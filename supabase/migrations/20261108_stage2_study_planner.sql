  if c.code is null then return jsonb_build_object('ok', false, 'error', 'UNAUTHORIZED'); end if;
  delete from public.ha_push_subs where code = c.code and endpoint = p_endpoint;
  return jsonb_build_object('ok', true);
end $$;

-- Scheduler: runs every minute. Dedupe keys (unique) make every reminder fire at most once per item/day.
create or replace function public.ha_study_tick()
returns int language plpgsql security definer set search_path = '' as $$
declare r record; today date; startts timestamp; made int := 0; got int; cnt int; undone int; lines text; ln timestamp;
begin
  -- per-item reminders
  for r in
    select i.*, coalesce(s.tz, 'Africa/Cairo') as tz, coalesce(s.rest_days, '{}'::int[]) as rest
    from public.ha_study_items i left join public.ha_study_settings s on s.code = i.code
    where i.enabled and coalesce(s.notify_enabled, true)
  loop
    ln := now() at time zone r.tz; today := ln::date;
    if not public.ha_study_occurs(r.enabled, r.repeat, r.days, r.once_date, r.rest, today) then continue; end if;
    startts := today + r.start_time;
    if r.remind_before_min > 0 and ln >= startts - make_interval(mins => r.remind_before_min) and ln < startts then
      insert into public.ha_user_notifications (code, kind, title, body, item_id, dedupe_key)
        values (r.code, 'before', 'استعد للمذاكرة', 'بعد ' || greatest(1, ceil(extract(epoch from (startts - ln)) / 60))::int || ' دقيقة: ' || r.subject || ' — ' || r.title, r.id, r.id::text || '|' || today || '|before')
        on conflict (dedupe_key) do nothing;
      get diagnostics got = row_count; made := made + got;
    end if;
    if ln >= startts and ln < startts + interval '10 minutes' then
      insert into public.ha_user_notifications (code, kind, title, body, item_id, dedupe_key)
        values (r.code, 'start', 'حان الآن موعد مذاكرة ' || r.subject || '!', 'ابدأ مهمتك وحقق هدفك اليوم: ' || r.title, r.id, r.id::text || '|' || today || '|start')
        on conflict (dedupe_key) do nothing;
      get diagnostics got = row_count; made := made + got;
    end if;
    if ln >= startts + interval '15 minutes' and ln < startts + interval '120 minutes'
       and not exists (select 1 from public.ha_study_done d where d.item_id = r.id and d.day = today) then
      insert into public.ha_user_notifications (code, kind, title, body, item_id, dedupe_key)
        values (r.code, 'late', 'تأخرت عن مهمتك', 'لسه فيه وقت! ابدأ الآن: ' || r.subject || ' — ' || r.title, r.id, r.id::text || '|' || today || '|late')
        on conflict (dedupe_key) do nothing;
      get diagnostics got = row_count; made := made + got;
    end if;
  end loop;

  -- per-student daily summary (at the chosen time) and unfinished-task reminder (at 21:00)
  for r in
    select distinct i.code, coalesce(s.tz, 'Africa/Cairo') as tz, coalesce(s.rest_days, '{}'::int[]) as rest,
           coalesce(s.daily_summary, true) as dsum, coalesce(s.summary_time, '07:00'::time) as stime
    from public.ha_study_items i left join public.ha_study_settings s on s.code = i.code
    where i.enabled and coalesce(s.notify_enabled, true)
  loop
    ln := now() at time zone r.tz; today := ln::date;
    if r.dsum and ln::time >= r.stime and ln::time < r.stime + interval '10 minutes' then
      select count(*), string_agg(to_char(i.start_time, 'HH24:MI') || ' ' || i.subject || ' — ' || i.title, E'\n' order by i.start_time)
        into cnt, lines from public.ha_study_items i where i.code = r.code and public.ha_study_occurs(i.enabled, i.repeat, i.days, i.once_date, r.rest, today);
      if cnt > 0 then
        insert into public.ha_user_notifications (code, kind, title, body, dedupe_key)
          values (r.code, 'summary', 'جدول مذاكرتك اليوم (' || cnt || ')', lines, r.code || '|' || today || '|summary') on conflict (dedupe_key) do nothing;
        get diagnostics got = row_count; made := made + got;
      end if;
    end if;
    if ln::time >= '21:00' and ln::time < '21:10' then
      select count(*) into undone from public.ha_study_items i
        where i.code = r.code and public.ha_study_occurs(i.enabled, i.repeat, i.days, i.once_date, r.rest, today) and i.start_time < ln::time
          and not exists (select 1 from public.ha_study_done d where d.item_id = i.id and d.day = today);
      if undone > 0 then
        insert into public.ha_user_notifications (code, kind, title, body, dedupe_key)
          values (r.code, 'incomplete', 'مهام لم تكتمل اليوم', 'عندك ' || undone || ' من مهام اليوم لم تُكمل بعد. لسه فيه وقت!', r.code || '|' || today || '|incomplete') on conflict (dedupe_key) do nothing;
        get diagnostics got = row_count; made := made + got;
      end if;
    end if;
  end loop;

  delete from public.ha_user_notifications where created_at < now() - interval '60 days';
  return made;
end $$;

-- Internal helpers for the push dispatcher (service role only).
create or replace function public.ha_push_cron_ok(p_secret text)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from vault.decrypted_secrets where name = 'ha_cron_secret' and decrypted_secret = p_secret and coalesce(p_secret, '') <> '');
$$;

create or replace function public.ha_push_pending(p_limit int)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare out jsonb;
begin
  with picked as (
    update public.ha_user_notifications n set pushed_at = now()
    where n.id in (select id from public.ha_user_notifications where pushed_at is null and created_at > now() - interval '3 hours' order by created_at limit greatest(1, least(p_limit, 500)) for update skip locked)
    returning n.id, n.code, n.title, n.body, n.kind
  )
  select coalesce(jsonb_agg(jsonb_build_object('id', p.id, 'title', p.title, 'body', p.body, 'kind', p.kind,
      'subs', (select coalesce(jsonb_agg(jsonb_build_object('endpoint', s.endpoint, 'p256dh', s.p256dh, 'auth', s.auth)), '[]'::jsonb) from public.ha_push_subs s where s.code = p.code))), '[]'::jsonb)
    into out from picked p;
  update public.ha_user_notifications set pushed_at = now() where pushed_at is null and created_at <= now() - interval '3 hours';
  return out;
end $$;

create or replace function public.ha_push_remove(p_endpoints text[])
returns void language sql security definer set search_path = '' as $$
  delete from public.ha_push_subs where endpoint = any(p_endpoints);
$$;

-- One cron entry point: create reminders, then wake the dispatcher only if something is waiting to be pushed.
create or replace function public.ha_cron_minute()
returns void language plpgsql security definer set search_path = '' as $$
declare sec text;
begin
  perform public.ha_study_tick();
  if exists (select 1 from public.ha_user_notifications n where n.pushed_at is null and n.created_at > now() - interval '3 hours'
             and exists (select 1 from public.ha_push_subs s where s.code = n.code)) then
    select decrypted_secret into sec from vault.decrypted_secrets where name = 'ha_cron_secret';
    perform net.http_post(url := 'https://vmwfwyyrqbtwthakwqft.supabase.co/functions/v1/ha-push',
      headers := jsonb_build_object('Content-Type', 'application/json'),
      body := jsonb_build_object('action', 'dispatch', 'secret', sec));
  else
    update public.ha_user_notifications set pushed_at = now() where pushed_at is null;
  end if;
end $$;

do $$
begin
  if not exists (select 1 from vault.secrets where name = 'ha_cron_secret') then
    perform vault.create_secret(replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''), 'ha_cron_secret', 'shared secret for the push dispatcher');
  end if;
end $$;

do $$
declare f text;
begin
  foreach f in array array[
    'ha_study_get(text,text)','ha_study_save_item(text,text,jsonb)','ha_study_delete_item(text,text,uuid)','ha_study_set_done(text,text,uuid,date,boolean)',
    'ha_study_save_settings(text,text,text,int[],boolean,boolean,text)','ha_notif_mark_read(text,text,uuid[])','ha_push_subscribe(text,text,text,text,text)','ha_push_unsubscribe(text,text,text)'] loop
    execute format('revoke all on function public.%s from public', f);
    execute format('grant execute on function public.%s to anon, authenticated', f);
  end loop;
  foreach f in array array['ha_study_tick()','ha_cron_minute()','ha_study_occurs(boolean,text,int[],date,int[],date)','ha_push_cron_ok(text)','ha_push_pending(int)','ha_push_remove(text[])'] loop
    execute format('revoke all on function public.%s from public, anon, authenticated', f);
  end loop;
  grant execute on function public.ha_push_cron_ok(text) to service_role;
  grant execute on function public.ha_push_pending(int) to service_role;
  grant execute on function public.ha_push_remove(text[]) to service_role;
end $$;

select cron.schedule('ha-cron-minute', '* * * * *', $$select public.ha_cron_minute()$$);
