create or replace function public.ha_push_subscribe(p_code text, p_device text, p_endpoint text, p_p256dh text, p_auth text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare c public.ha_codes; n int;
begin
  c := public.ha_resolve(p_code, p_device);
  if c.code is null then return jsonb_build_object('ok', false, 'error', 'UNAUTHORIZED'); end if;
  if coalesce(p_endpoint, '') !~ '^https://' or length(p_endpoint) > 1000 or coalesce(p_p256dh, '') = '' or coalesce(p_auth, '') = '' then
    return jsonb_build_object('ok', false, 'error', 'INVALID');
  end if;
  select count(*) into n from public.ha_push_subs where code = c.code and endpoint <> p_endpoint;
  if n >= 10 then delete from public.ha_push_subs where id in (select id from public.ha_push_subs where code = c.code order by created_at limit n - 9); end if;
  insert into public.ha_push_subs (code, endpoint, p256dh, auth) values (c.code, p_endpoint, p_p256dh, p_auth)
    on conflict (endpoint) do update set code = excluded.code, p256dh = excluded.p256dh, auth = excluded.auth;
  return jsonb_build_object('ok', true);
end $$;

create or replace function public.ha_push_unsubscribe(p_code text, p_device text, p_endpoint text)
